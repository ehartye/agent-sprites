import { test, expect, beforeEach, afterEach } from 'vitest';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtempSync, rmSync, readFileSync, writeFileSync, cpSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createServer } from 'node:http';
import sharp from 'sharp';
import { constructionReplayFixture } from '../helpers/construction-replay-fixture.js';
const exec = promisify(execFile);
let dir, sentinel, contacts;
beforeEach(async () => {
  dir = mkdtempSync(join(tmpdir(), 'sprite-replay-cli-')); contacts = 0;
  sentinel = createServer((_req, res) => { contacts++; res.setHeader('Content-Type', 'application/json'); res.end('{"service":"offline-workflow-must-not-contact"}'); });
  await new Promise(resolve => sentinel.listen(0, '127.0.0.1', resolve));
});
afterEach(async () => { await new Promise(resolve => sentinel.close(resolve)); rmSync(dir, { recursive: true, force: true }); });
const cli = (...args) => exec(process.execPath, [resolve('scripts/sprite.js'), ...args], { env: { ...process.env, SPRITE_PORT: String(sentinel.address().port) }, windowsHide: true, timeout: 10000 });
test('offline CLI lists construction sources and exports a selected step without altering the saved project', async () => {
  const built = await constructionReplayFixture(dir), before = readFileSync(built.artifacts.project);
  const meta = JSON.parse((await cli('replay', built.artifacts.project, '--list', '--json')).stdout);
  const eye = meta.steps.find(step => step.operationIndex === 2);
  const rendered = JSON.parse((await cli('replay', built.artifacts.project, '--cell', '0,0', '--step', String(eye.step), '--out', join(dir, 'review'), '--json')).stdout);
  expect(rendered.changedPixels).toBe(1);
  expect((await sharp(rendered.artifacts.after).metadata()).width).toBe(8);
  expect(readFileSync(built.artifacts.project)).toEqual(before);
  expect(contacts).toBe(0);
  await expect(cli('replay', built.artifacts.project, '--cell', '0,0', '--step', String(eye.step), '--out', join(dir, 'review'))).rejects.toMatchObject({ code: 1 });
}, 15000);
test('source-linked contribution identifies a misplaced eye and a rebuilt correction changes its source identity', async () => {
  const example = join(dir, 'example'); cpSync(resolve('examples/construction-replay'), example, { recursive: true });
  const sourcePath = join(example, 'operations.json'), operations = JSON.parse(readFileSync(sourcePath, 'utf8'));
  operations[2].x = 14; writeFileSync(sourcePath, JSON.stringify(operations));
  const config = join(example, 'sprite-project.json');
  const first = JSON.parse((await cli('build', config, '--json')).stdout); expect(first.ok, JSON.stringify(first.errors)).toBe(true);
  const metadata = JSON.parse((await cli('replay', first.artifacts.project, '--list', '--json')).stdout);
  const eye = metadata.steps.find(step => step.operationIndex === 2);
  expect(eye.source).toMatchObject({ path: 'operations.json', pointer: '/2' });
  expect(eye.label).toContain('eye');
  const selected = JSON.parse((await cli('replay', first.artifacts.project, '--cell', '0,0', '--step', String(eye.step), '--out', join(dir, 'bad-eye'), '--json')).stdout);
  expect(selected.changedBounds.x).toBe(14);
  const originalSourceHash = eye.source.sha256;
  operations[2].x = 6; writeFileSync(sourcePath, JSON.stringify(operations));
  const corrected = JSON.parse((await cli('build', config, '--json')).stdout); expect(corrected.ok).toBe(true);
  const correctedMeta = JSON.parse((await cli('replay', corrected.artifacts.project, '--list', '--json')).stdout);
  expect(correctedMeta.steps.find(step => step.operationIndex === 2).source.sha256).not.toBe(originalSourceHash);
  const correctedView = JSON.parse((await cli('replay', corrected.artifacts.project, '--cell', '0,0', '--step', String(eye.step), '--out', join(dir, 'fixed-eye'), '--json')).stdout);
  expect(correctedView.changedBounds.x).toBe(6);
}, 20000);
